import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, relative } from 'node:path'
import { test } from 'node:test'
import {
  REPO_ROOT, applySync, checkSync, copyEntries, declaredSource, discoverCopies, headerFor, renderCopy, stripHeader,
} from './sync-shared.mjs'

test('header/strip round-trips generated TypeScript copies', () => {
  const source = 'export const x = 1\n'
  const sourceRel = 'shared/host/http.ts'
  const rendered = renderCopy(source, 'http.ts', sourceRel)
  assert.ok(rendered.startsWith(headerFor('http.ts', sourceRel)))
  assert.equal(stripHeader(rendered, 'http.ts', sourceRel), source)
  assert.equal(stripHeader('mangled ' + rendered.slice(10), 'http.ts', sourceRel), undefined)
})

test('the declared shared source is parsed from the generated header', () => {
  assert.equal(declaredSource(renderCopy('x\n', 'loopback.ts', 'shared/host/loopback.ts')), 'shared/host/loopback.ts')
  assert.equal(declaredSource('export const x = 1\n'), undefined)
  assert.equal(declaredSource('// Generated by hand.\n'), undefined)
})

/**
 * Frozen snapshot of the copies the tree actually carries. Discovery is
 * header-driven, so a copy that loses its header (or is deleted) simply
 * vanishes from the scan and `checkSync` would pass vacuously — the same
 * failure mode that made the previous empty-manifest gate decorative. Dropping
 * a copy therefore has to be a deliberate edit here.
 */
const EXPECTED_COPIES = [
  'packages/dsh-web-all/src/client/conversation/git-graph/sse-leader.ts',
  'packages/dsh-web-all/src/host/services/codex-bridge/http.ts',
  'packages/dsh-web-all/src/host/services/codex-bridge/loopback.ts',
  'packages/dsh-web-all/src/host/services/remote-web-ui/server-mode/dsh-home.ts',
  'packages/dsh-web-all/src/host/services/remote-web-ui/server-mode/http.ts',
  'packages/dsh-web-all/src/host/services/worktree/git-runner.ts',
]

test('every generated copy in the tree is discovered, and none disappears silently', async () => {
  const targets = (await discoverCopies()).map(entry => relative(REPO_ROOT, entry.target)).sort()
  assert.deepEqual(targets, EXPECTED_COPIES,
    'a generated copy was added, deleted, or lost its header: restore it or update this snapshot deliberately')
  for (const entry of await discoverCopies()) {
    const source = await readFile(entry.source, 'utf8')
    assert.ok(source.length > 0, `${entry.sourceRel} is empty`)
  }
})

test('the live tree is in sync with every shared source it declares', async () => {
  assert.deepEqual(await checkSync(), [])
})

test('checkSync fails closed on a drifted copy and on a missing shared source', async () => {
  const root = await mkdtemp(join(tmpdir(), 'sync-shared-'))
  try {
    await mkdir(join(root, 'shared/host'), { recursive: true })
    await mkdir(join(root, 'packages/demo/src'), { recursive: true })
    await writeFile(join(root, 'shared/host/loopback.ts'), 'export const x = 1\n')

    const copy = join(root, 'packages/demo/src/loopback.ts')
    await writeFile(copy, renderCopy('export const x = 1\n', 'loopback.ts', 'shared/host/loopback.ts'))
    assert.deepEqual(await checkSync(root), [])

    // Falsification: drift the copy and the gate must name it.
    await writeFile(copy, renderCopy('export const x = 2\n', 'loopback.ts', 'shared/host/loopback.ts'))
    assert.deepEqual(await checkSync(root), [{ target: copy, reason: 'content drifted from shared source' }])

    // Falsification: a copy whose declared shared source does not exist.
    await writeFile(copy, renderCopy('export const x = 1\n', 'loopback.ts', 'shared/host/absent.ts'))
    assert.deepEqual(await checkSync(root), [{ target: copy, reason: 'declared shared source is missing: shared/host/absent.ts' }])

    // Recovery: once the declared source exists, applySync regenerates the copy.
    await writeFile(join(root, 'shared/host/absent.ts'), 'export const x = 3\n')
    assert.equal(await applySync(root), 1, 'applySync regenerates from the declared source')
    assert.deepEqual(await checkSync(root), [], 'the regenerated copy matches its declared source')
    assert.equal(copyEntries(root).length, 0, 'the explicit manifest stays empty in this repository')
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})