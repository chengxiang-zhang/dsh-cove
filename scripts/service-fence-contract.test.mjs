import test from 'node:test'
import assert from 'node:assert/strict'
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, posix, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const SERVICES = join(ROOT, 'packages/dsh-web-all/src/host/services')

/**
 * Static half of the remote-access contract (docs/remote-access.md). The
 * runtime half lives in packages/dsh-web-all tests, which drive each family
 * with a forged Host, a sessionless remote browser, a declared authority with a
 * session, and a loopback page.
 *
 * This gate exists because the two reported regressions were both invisible to
 * per-file review: the worktree and workspace-model reads passed no fence at
 * all, and the pairing guard used a socket-only loopback check that a same-host
 * reverse proxy satisfies for every remote browser. A new privileged capability
 * directory must therefore adopt one of the shared fences, and a locally
 * defined loopback predicate must delegate to the shared implementation.
 */

/** Files that define or register web routes, per service directory. */
function routeDirectories() {
  const found = new Map()
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        walk(path)
        continue
      }
      if (!name.endsWith('.ts')) continue
      const text = readFileSync(path, 'utf8')
      const definesRoutes = /kind: '(exact|prefix)'/u.test(text)
        || /webServer\.register\(/u.test(text)
        || /registerUpgrade\(/u.test(text)
      if (!definesRoutes) continue
      const service = relative(SERVICES, dir).split('/')[0]
      const entry = found.get(service) ?? { files: [], text: '' }
      entry.files.push(relative(SERVICES, path))
      entry.text += text
      found.set(service, entry)
    }
  }
  walk(SERVICES)
  return found
}

/**
 * Every privileged service directory and the shared fence token a reviewer must
 * find in it. Adding a directory that defines routes fails the first assertion
 * until it is listed here and fences its surface.
 */
const PRIVILEGED_FENCE_TOKEN = new Map([
  ['access-trust', null],
  ['codex-bridge', 'isLoopbackRequest'],
  ['git-graph', 'accessTrustOf'],
  ['lark-inbox', 'accessTrustOf'],
  ['memoir', 'accessTrustOf'],
  ['notify', 'accessTrustOf'],
  ['playwright-sessions', 'accessTrustOf'],
  ['remote-access', 'isTrusted'],
  ['remote-web-ui', 'isLoopbackRequest'],
  ['right-pane', 'accessTrustOf'],
  ['schedule-mode', 'accessTrustOf'],
  ['ssh', 'accessTrustOf'],
  ['worktree', 'accessTrustOf'],
])

/** Files allowed to define a loopback predicate, and why. */
const PREDICATE_OWNERS = new Map([
  ['shared/host/loopback.ts', 'the single shared implementation'],
  ['packages/dsh-web-all/src/host/services/access-trust/trust.ts', 'the plugin admission rule (audited owner)'],
  ['packages/dsh-web-all/src/core/right-pane/protocol.ts', 'browser URL classification (not a request fence)'],
  ['packages/dsh-web-all/src/client/trust.ts', 'browser-side module-context gate'],
])
const LOOPBACK_COPY_SOURCE = 'shared/host/loopback.ts'

/**
 * Fence expressions a route-owning file may use. `isLoopbackRequest` is only
 * accepted from the audited owner or from a verified generated copy of the
 * shared implementation: a same-named hand-written predicate next to a route is
 * exactly the defect this gate exists to catch (a socket-only check behind a
 * same-host proxy, or one without browser same-origin markers).
 */
const FENCE_CALLS = /\b(?:accessTrustOf|isTrustedHostRequest|isLoopbackAdmin|isTrusted)\s*\(/u
const SHARED_PREDICATE_CALL = /\bisLoopbackRequest\s*\(/u
const GENERATED_HEADER = /^\/\/ Generated by scripts\/sync-shared\.mjs from shared\/host\/loopback\.ts\./u
/**
 * Any request-level function that decides loopback trust, under any name: a
 * copy named `isStrictLoopbackRequest` is the same duplication as one named
 * `isLoopbackRequest`, and the previous regex could not see it. Predicates over
 * a bare hostname (URL classification) are not request fences and are not
 * matched.
 */
const DEFINES_PREDICATE = /(?:export\s+)?function\s+(is[A-Za-z0-9_]*Loopback[A-Za-z0-9_]*)\s*\(\s*[A-Za-z0-9_]*\s*:\s*IncomingMessage/u
/**
 * A wrapper that delegates to the shared implementation is not a duplicate:
 * it must import the shared predicate or call the admission rule, rather than
 * merely mention its own name.
 */
const DELEGATES_TO_SHARED = /import\s*\{[^}]*\bisLoopbackRequest\b|\bisTrustedHostRequest\s*\(|\baccessTrustOf\s*\(/u

/** Route-owning file: it writes handlers (route literals) or registers an upgrade. */
function ownsRoutes(text) {
  return /kind: '(?:exact|prefix)'/u.test(text) || /registerUpgrade\s*\(/u.test(text)
}

/** Whether the file proves it is entitled to call the strict shared predicate. */
function importsSharedPredicate(file, copies) {
  if (GENERATED_HEADER.test(file.text)) return true
  const specifier = /import\s*\{[^}]*\bisLoopbackRequest\b[^}]*\}\s*from\s*'([^']+)'/u.exec(file.text)?.[1]
  if (specifier === undefined) return false
  if (/access-trust/u.test(specifier)) return true
  // A relative import satisfies the rule only when it resolves to a file that
  // actually is a generated copy of the shared implementation.
  const resolved = resolveModule(file.path, specifier)
  return resolved !== undefined && copies.has(resolved)
}

/** Resolve a relative import specifier against the importing file's directory. */
function resolveModule(fromPath, specifier) {
  if (!specifier.startsWith('.')) return undefined
  const base = posix.dirname(fromPath)
  const joined = posix.normalize(posix.join(base, specifier))
  return joined.endsWith('.ts') ? joined : `${joined}.ts`
}

/**
 * The whole static rule, over `{ path, text }` records: every route-owning file
 * carries its own fence, and no file outside the audited owners defines a
 * loopback predicate.
 * @param files - candidate files with their repository-relative paths.
 * @returns the offenders, each naming the rule it broke.
 */
export function auditFenceSources(files) {
  const copies = new Set(files
    .filter(file => /^\/\/ Generated by scripts\/sync-shared\.mjs from shared\/host\/loopback\.ts\./u.test(file.text))
    .map(file => file.path))
  const offenders = []
  for (const file of files) {
    if (ownsRoutes(file.text)) {
      const fenced = FENCE_CALLS.test(file.text)
        || (SHARED_PREDICATE_CALL.test(file.text) && importsSharedPredicate(file, copies))
      if (!fenced) offenders.push(`${file.path}: route-owning file passes no shared fence`)
    }
    if (DEFINES_PREDICATE.test(file.text) && !PREDICATE_OWNERS.has(file.path)) {
      if (!copies.has(file.path) && !DELEGATES_TO_SHARED.test(file.text)) {
        offenders.push(`${file.path}: defines a loopback predicate outside the audited owners`)
      }
    }
  }
  return offenders
}

test('every service directory that defines web routes pins a shared fence token', () => {
  const found = routeDirectories()
  const undocumented = [...found.keys()].filter(service => !PRIVILEGED_FENCE_TOKEN.has(service)).sort()
  assert.deepEqual(undocumented, [],
    'new route directory: adopt docs/remote-access.md invariant 2 and pin its fence token here')

  for (const [service, token] of PRIVILEGED_FENCE_TOKEN) {
    const entry = found.get(service)
    if (token === null) {
      assert.equal(entry, undefined, `${service} is pinned as route-free; remove it or give it a fence token`)
      continue
    }
    assert.ok(entry !== undefined, `${service} defines routes but is missing from the scan`)
    assert.ok(entry.text.includes(token),
      `${service} must reference the shared fence \`${token}\` (files: ${entry.files.join(', ')})`)
  }
})

test('the static rule flags an unfenced route file and a hand-written predicate', () => {
  const offenders = auditFenceSources([
    { path: 'packages/dsh-web-all/src/host/services/demo/routes.ts', text: "export const routes = [{ kind: 'exact', path: '/api/demo', handler: async (req, res) => { void req; void res } }]\n" },
    { path: 'packages/dsh-web-all/src/host/services/demo/predicate.ts', text: 'export function isLoopbackRequest(request: IncomingMessage): boolean { return request.socket.remoteAddress === "127.0.0.1" }\n' },
  ])
  assert.deepEqual(offenders, [
    'packages/dsh-web-all/src/host/services/demo/routes.ts: route-owning file passes no shared fence',
    'packages/dsh-web-all/src/host/services/demo/predicate.ts: defines a loopback predicate outside the audited owners',
  ])

  // A route file that goes through the audited admission rule is fine.
  assert.deepEqual(auditFenceSources([{
    path: 'packages/dsh-web-all/src/host/services/demo/routes.ts',
    text: "import { accessTrustOf } from '../access-trust/index.ts'\nexport const routes = [{ kind: 'exact', path: '/api/demo', handler: async (req, res) => { if (!accessTrustOf(ctx).isTrusted(req)) return; void res } }]\n",
  }]), [])

  // Calling the strict predicate without proving where it came from is not.
  assert.deepEqual(auditFenceSources([{
    path: 'packages/dsh-web-all/src/host/services/demo/routes.ts',
    text: "export const routes = [{ kind: 'exact', path: '/api/demo', handler: async (req, res) => { if (!isLoopbackRequest(req)) return; void res } }]\n",
  }]), ['packages/dsh-web-all/src/host/services/demo/routes.ts: route-owning file passes no shared fence'])

  // The generated copy satisfies the predicate rule and may be called directly.
  const copy = '// Generated by scripts/sync-shared.mjs from shared/host/loopback.ts. Do not edit this copy; edit the shared source and run "node scripts/sync-shared.mjs".\nexport function isLoopbackRequest(request: IncomingMessage): boolean { return request.socket.remoteAddress === "127.0.0.1" }\n'
  assert.deepEqual(auditFenceSources([{ path: 'packages/dsh-web-all/src/host/services/demo/loopback.ts', text: copy }]), [])

  // A wrapper that delegates to the shared implementation is allowed, even
  // under a loopback name; a hostname classifier is not a request predicate.
  assert.deepEqual(auditFenceSources([{
    path: 'packages/dsh-web-all/src/host/services/demo/fence.ts',
    text: "import { isLoopbackRequest } from '../access-trust/trust.ts'\nexport function isLoopbackAdmin(request: IncomingMessage): boolean { return isLoopbackRequest(request) }\n",
  }]), [])
  assert.deepEqual(auditFenceSources([{
    path: 'packages/dsh-web-all/src/host/services/demo/policy.ts',
    text: 'function isLoopbackHost(hostname: string): boolean { return hostname === "localhost" }\n',
  }]), [])

  // A hand-written request predicate that does not delegate is flagged.
  assert.deepEqual(auditFenceSources([{
    path: 'packages/dsh-web-all/src/host/services/demo/strict.ts',
    text: 'export function isStrictLoopbackRequest(request: IncomingMessage): boolean { return request.socket.remoteAddress === "127.0.0.1" }\n',
  }]), ['packages/dsh-web-all/src/host/services/demo/strict.ts: defines a loopback predicate outside the audited owners'])
})

test('the live tree fences every route-owning file', () => {
  const files = []
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        walk(path)
        continue
      }
      if (!name.endsWith('.ts') && !name.endsWith('.tsx')) continue
      files.push({ path: relative(ROOT, path), text: readFileSync(path, 'utf8') })
    }
  }
  for (const dir of ['host', 'client', 'core']) walk(join(ROOT, 'packages/dsh-web-all/src', dir))
  assert.deepEqual(auditFenceSources(files), [],
    'a route-owning file must carry its own fence, and loopback predicates belong to the audited owners')
})

test('a locally defined loopback predicate delegates to the shared implementation', () => {
  const offenders = []
  for (const [service, entry] of routeDirectories()) {
    if (!/function isLoopback\(|const isLoopback =/u.test(entry.text)) continue
    if (!/isLoopbackRequest|isLoopbackClient/u.test(entry.text)) offenders.push(service)
  }
  assert.deepEqual(offenders, [],
    'a socket-only loopback predicate is not a trust boundary behind a same-host reverse proxy: use the shared rule')
})

test('the plain-HTTP boot row has one owner', () => {
  const owners = []
  for (const dir of ['host', 'client', 'core']) {
    const walk = (base) => {
      for (const name of readdirSync(base)) {
        const path = join(base, name)
        if (statSync(path).isDirectory()) {
          if (name === 'node_modules') continue
          walk(path)
          continue
        }
        if (!name.endsWith('.ts')) continue
        const text = readFileSync(path, 'utf8')
        if (/UUID_POLYFILL_SCRIPT|CLIPBOARD_SHIM_SCRIPT/u.test(text)) owners.push(relative(ROOT, path))
      }
    }
    walk(join(ROOT, 'packages/dsh-web-all/src', dir))
  }
  assert.deepEqual(owners.sort(), [
    'packages/dsh-web-all/src/host/services/remote-access/boot-scripts.ts',
    'packages/dsh-web-all/src/host/services/remote-access/index.ts',
  ], 'the uuid polyfill and the clipboard shim belong to the remote-access domain only')
})

test('the reverse-proxy boot path and marker are shared constants', () => {
  const paths = readFileSync(join(ROOT, 'packages/dsh-web-all/src/core/remote-access/paths.ts'), 'utf8')
  assert.match(paths, /HOST_ACCESS_BOOT_PATH = '\/web-all\/remote-access\/boot\.js'/u)
  assert.match(paths, /HOST_ACCESS_SESSION_PATH = '\/api\/dsh-access\/session'/u)
  assert.match(paths, /HOST_ACCESS_MARKER_COOKIE = 'dsh_access_host'/u)
  const client = readFileSync(join(ROOT, 'packages/dsh-web-all/src/client/trust.ts'), 'utf8')
  assert.ok(client.includes("from '../core/remote-access/paths.ts'"),
    'the browser half must share the constants instead of duplicating the paths')
})