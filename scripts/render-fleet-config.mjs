#!/usr/bin/env node
/**
 * Render the client fleet facts from one configuration file.
 *
 * The same handful of values decides where a fresh client enrolls, which DNS
 * domain NetBird Cloud peers use, and which update/bootstrap origins the mobile
 * and desktop clients carry. They used to be literals in each client, which is
 * how the desktop and the phone ended up describing different deployments.
 *
 * `config/fleet.json` is the single source:
 *
 * - the management address a build without a deployment value dials;
 * - the NetBird Cloud peer DNS domain (and the host suffixes that mean "cloud");
 * - the update channel and bootstrap origins;
 * - the sign-in flow preference (`auto`, `device` or `pkce`).
 *
 * The DSH zone name is not duplicated here: `tools/dsh-netbird/machines.json`
 * owns the self-hosted fleet inventory, and this renderer derives the zone from
 * its `domainPattern` like `dsh-netbird-mobile-registry.mjs` does.
 *
 * Usage:
 *   node scripts/render-fleet-config.mjs            # write generated files
 *   node scripts/render-fleet-config.mjs --check    # fail on drift
 *   node scripts/render-fleet-config.mjs --get managementUrl
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const FLEET_CONFIG_PATH = 'config/fleet.json';
export const MACHINES_PATH = 'tools/dsh-netbird/machines.json';
export const TS_OUTPUT = 'tools/netbird-client/src/generated/fleetConfig.ts';
export const MJS_OUTPUT = 'tools/anywhere-agent/src/generated/fleetConfig.mjs';
export const ANDROID_XML_OUTPUT =
  'tools/netbird-client/android/app/src/main/res/values/fleet_cloud_config.xml';
export const IOS_PLIST_PATH = 'tools/netbird-client/ios/NetBirdPortal/Info.plist';
export const ANDROID_SECURITY_CONFIG_PATH =
  'tools/netbird-client/android/app/src/main/res/xml/network_security_config.xml';

const GENERATED_NOTE =
  'Generated by scripts/render-fleet-config.mjs from config/fleet.json. Do not edit.';

/** Reads one JSON file relative to the repository root. */
function readJson(root, relativePath) {
  return JSON.parse(readFileSync(join(root, relativePath), 'utf8'));
}

/** The DSH zone the self-hosted inventory declares, for example `netbird`. */
export function dshZoneOfPattern(pattern) {
  const placeholder = '<netbird-machine-name>';
  if (typeof pattern !== 'string' || !pattern.includes(placeholder)) {
    throw new Error(`${MACHINES_PATH}: domainPattern must contain ${placeholder}`);
  }
  const suffix = pattern.slice(pattern.lastIndexOf(placeholder) + placeholder.length);
  const zone = suffix.startsWith('.') ? suffix.slice(1) : suffix;
  if (zone === '' || zone.includes('<')) {
    throw new Error(`${MACHINES_PATH}: domainPattern must end in a literal zone`);
  }
  return zone;
}

/** Validates the configuration and returns the normalized facts. */
export function loadFleetConfig(root = repoRoot) {
  const config = readJson(root, FLEET_CONFIG_PATH);
  const management = config.management ?? {};
  const dns = config.dns ?? {};
  const bootstrap = config.bootstrap ?? {};
  const auth = config.auth ?? {};

  const managementUrl = String(management.url ?? '').trim();
  if (!/^https?:\/\//i.test(managementUrl)) {
    throw new Error(`${FLEET_CONFIG_PATH}: management.url must be an http(s) URL`);
  }
  const mode = String(management.mode ?? '').trim();
  if (mode !== 'cloud' && mode !== 'self-hosted') {
    throw new Error(`${FLEET_CONFIG_PATH}: management.mode must be cloud or self-hosted`);
  }
  const cloudDomain = String(dns.cloudDomain ?? '').trim().toLowerCase();
  if (!/^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$/.test(cloudDomain)) {
    throw new Error(`${FLEET_CONFIG_PATH}: dns.cloudDomain must be a DNS name`);
  }
  const cloudHostSuffixes = (management.cloudHostSuffixes ?? []).map(value => String(value).trim().toLowerCase());
  if (cloudHostSuffixes.length === 0 || cloudHostSuffixes.some(value => value === '')) {
    throw new Error(`${FLEET_CONFIG_PATH}: management.cloudHostSuffixes must be a non-empty list`);
  }
  const updateBaseUrl = String(bootstrap.updateBaseUrl ?? '').trim();
  if (!/^https?:\/\/.+\/$/.test(updateBaseUrl)) {
    throw new Error(`${FLEET_CONFIG_PATH}: bootstrap.updateBaseUrl must end with a slash`);
  }
  const overlayUpdateBaseUrl = String(bootstrap.overlayUpdateBaseUrl ?? '').trim();
  if (!/^https?:\/\/.+\/$/.test(overlayUpdateBaseUrl)) {
    throw new Error(`${FLEET_CONFIG_PATH}: bootstrap.overlayUpdateBaseUrl must end with a slash`);
  }
  const configUrlsOf = (key) => {
    const list = (bootstrap[key] ?? []).map(value => String(value).trim());
    if (list.length === 0 || list.some(value => !/^https?:\/\//i.test(value))) {
      throw new Error(`${FLEET_CONFIG_PATH}: bootstrap.${key} must be http(s) URLs`);
    }
    return list;
  };
  // The two clients reach the overlay differently: the phone's netstack resolver
  // does not answer overlay names before the tunnel is up, so its fallback is a
  // literal peer address; the desktop proxy does resolve them.
  const mobileConfigUrls = configUrlsOf('mobileConfigUrls');
  const desktopConfigUrls = configUrlsOf('desktopConfigUrls');
  const flow = String(auth.flow ?? 'auto').trim();
  if (flow !== 'auto' && flow !== 'device' && flow !== 'pkce') {
    throw new Error(`${FLEET_CONFIG_PATH}: auth.flow must be auto, device or pkce`);
  }

  const inventory = readJson(root, MACHINES_PATH);
  const zone = dshZoneOfPattern(inventory.domainPattern);

  return {
    mode,
    managementUrl,
    cloudDomain,
    cloudHostSuffixes,
    updateBaseUrl,
    overlayUpdateBaseUrl,
    manifestUrl: `${updateBaseUrl}version.json`,
    apkBaseUrl: updateBaseUrl,
    mobileConfigUrls,
    desktopConfigUrls,
    flow,
    zone,
  };
}

/** The rendered contents keyed by repository-relative path. */
export function renderFleetConfig(root = repoRoot) {
  const facts = loadFleetConfig(root);
  const baseValues = {
    MANAGEMENT_URL: facts.managementUrl,
    CLOUD_DNS_DOMAIN: facts.cloudDomain,
    CLOUD_HOST_SUFFIXES: facts.cloudHostSuffixes,
    UPDATE_BASE_URL: facts.updateBaseUrl,
    OVERLAY_UPDATE_BASE_URL: facts.overlayUpdateBaseUrl,
    MANIFEST_URL: facts.manifestUrl,
    APK_BASE_URL: facts.apkBaseUrl,
    DSH_ZONES: [facts.zone],
    AUTH_FLOW: facts.flow,
    MANAGEMENT_MODE: facts.mode,
  };
  // Each client gets the bootstrap origins it can actually reach: the phone
  // cannot resolve overlay names before the tunnel is up, the desktop proxy can.
  const tsValues = { ...baseValues, BOOTSTRAP_CONFIG_URLS: facts.mobileConfigUrls };
  const mjsValues = { ...baseValues, BOOTSTRAP_CONFIG_URLS: facts.desktopConfigUrls };
  const renderModule = (values, cast) => [
    `// ${GENERATED_NOTE}`,
    '',
    `export const FLEET_CONFIG = ${JSON.stringify(values, null, 2)}${cast};`,
    '',
    ...Object.keys(values).map(key => `export const ${key} = FLEET_CONFIG.${key};`),
    '',
  ].join('\n');

  const ts = renderModule(tsValues, ' as const');
  const mjs = renderModule(mjsValues, '');

  const xml = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${GENERATED_NOTE} -->`,
    '<resources>',
    `    <string name="fleet_cloud_dns_domain">${facts.cloudDomain}</string>`,
    '    <string-array name="fleet_cloud_host_suffixes">',
    ...facts.cloudHostSuffixes.map(suffix => `        <item>${suffix}</item>`),
    '    </string-array>',
    '</resources>',
    '',
  ].join('\n');

  const plistSource = readFileSync(join(root, IOS_PLIST_PATH), 'utf8');
  const plist = setPlistString(
    setPlistString(plistSource, 'AWManagementURL', facts.managementUrl),
    'AWCloudDnsDomain',
    facts.cloudDomain,
  );

  return {
    [TS_OUTPUT]: ts,
    [MJS_OUTPUT]: mjs,
    [ANDROID_XML_OUTPUT]: xml,
    [IOS_PLIST_PATH]: plist,
  };
}

/** Replaces one `<key>name</key><string>value</string>` pair in an Info.plist. */
export function setPlistString(plist, key, value) {
  const pattern = new RegExp(`(<key>${key}</key>\\s*<string>)([^<]*)(</string>)`);
  if (!pattern.test(plist)) {
    throw new Error(`${IOS_PLIST_PATH}: missing ${key}`);
  }
  return plist.replace(pattern, (_match, before, _current, after) => `${before}${value}${after}`);
}

/** Problems that mean a generated file (or a hand-kept carrier) drifted. */
export function checkFleetConfig(root = repoRoot) {
  const problems = [];
  const rendered = renderFleetConfig(root);
  for (const [relativePath, expected] of Object.entries(rendered)) {
    let actual;
    try {
      actual = readFileSync(join(root, relativePath), 'utf8');
    } catch {
      problems.push(`${relativePath}: missing; run scripts/render-fleet-config.mjs`);
      continue;
    }
    if (actual !== expected) {
      problems.push(`${relativePath}: differs from config/fleet.json; run scripts/render-fleet-config.mjs`);
    }
  }

  const facts = loadFleetConfig(root);
  const securityConfig = readFileSync(join(root, ANDROID_SECURITY_CONFIG_PATH), 'utf8');
  if (!securityConfig.includes(`>${facts.cloudDomain}</domain>`)) {
    problems.push(
      `${ANDROID_SECURITY_CONFIG_PATH}: missing the cleartext exception for ${facts.cloudDomain}`,
    );
  }
  const plist = readFileSync(join(root, IOS_PLIST_PATH), 'utf8');
  const ats = plist.slice(plist.indexOf('<key>NSExceptionDomains</key>'));
  if (!ats.includes(`<key>${facts.cloudDomain}</key>`)) {
    problems.push(`${IOS_PLIST_PATH}: missing the cleartext exception for ${facts.cloudDomain}`);
  }
  return problems;
}

function main() {
  const argv = process.argv.slice(2);
  if (argv.includes('--get')) {
    const dotted = argv[argv.indexOf('--get') + 1] ?? '';
    const facts = loadFleetConfig();
    const value = dotted.split('.').reduce((cursor, part) => (cursor == null ? cursor : cursor[part]), facts);
    if (value === undefined) {
      console.error(`render-fleet-config: no such key: ${dotted}`);
      process.exit(2);
    }
    console.log(typeof value === 'string' ? value : JSON.stringify(value));
    return;
  }
  if (argv.includes('--check')) {
    const problems = checkFleetConfig();
    if (problems.length === 0) {
      console.log('fleet config matches config/fleet.json');
      return;
    }
    for (const problem of problems) {
      console.error(`DRIFT ${problem}`);
    }
    process.exit(1);
  }
  for (const [relativePath, content] of Object.entries(renderFleetConfig())) {
    const target = join(repoRoot, relativePath);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    console.log(`render-fleet-config: ${relativePath}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
