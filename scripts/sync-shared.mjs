#!/usr/bin/env node
'use strict'

/**
 * sync-shared — mirror the few shared helpers consumed by current source and
 * asset packages.
 *
 * The copies are discovered from their own generated header instead of a
 * hand-maintained manifest: a manifest that drifts from the tree silently
 * stops checking anything (this script once carried an empty manifest while
 * eight generated copies remained in the tree, so `--check` passed vacuously).
 * Every file whose first line declares `from <sourceRel>` is checked, and a
 * copy whose declared source is missing is reported as drift.
 */
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
export const REPO_ROOT = resolve(SCRIPT_DIR, '..')
const MANIFEST = []
/** Directories scanned for generated copies, plus the names never descended into. */
const SCAN_ROOTS = ['packages', 'shared']
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'lib', 'out', 'coverage', '.turbo'])
const HEADER_PATTERN = /^(?:\/\/|\/\*) Generated by scripts\/sync-shared\.mjs from (\S+)\. Do not edit this copy/

/** Parse the source path a generated copy declares, or undefined when it is not one. */
export function declaredSource(text) {
  const match = HEADER_PATTERN.exec(text)
  return match === null ? undefined : match[1]
}

/** Every generated copy in the tree, keyed by its declared shared source. */
export async function discoverCopies(root = REPO_ROOT) {
  const found = []
  const walk = async (dir) => {
    let names
    try {
      names = await readdir(dir)
    } catch {
      return
    }
    for (const name of names.sort()) {
      const path = join(dir, name)
      const info = await stat(path)
      if (info.isDirectory()) {
        if (!SKIP_DIRS.has(name)) await walk(path)
        continue
      }
      if (!/\.(ts|tsx|mjs|cjs|js|css)$/.test(name)) continue
      const text = await readFile(path, 'utf8')
      const sourceRel = declaredSource(text)
      if (sourceRel === undefined) continue
      found.push({ sourceRel, target: path, file: name, source: join(root, sourceRel) })
    }
  }
  for (const name of SCAN_ROOTS) await walk(join(root, name))
  return found
}

export function copyEntries(root = REPO_ROOT) {
  return MANIFEST.flatMap(entry => entry.targets.map(target => ({ source: join(root, entry.source), target: join(root, target), file: entry.file, sourceRel: entry.source })))
}
export function headerFor(file, sourceRel = `shared/client/settings/${file}`) {
  const body = `Generated by scripts/sync-shared.mjs from ${sourceRel}. Do not edit this copy; edit the shared source and run "node scripts/sync-shared.mjs".`
  return file.endsWith('.css') ? `/* ${body} */` : `// ${body}`
}
export function renderCopy(sourceText, file, sourceRel) { return `${headerFor(file, sourceRel)}\n${sourceText}` }
export function stripHeader(rendered, file, sourceRel) {
  const header = headerFor(file, sourceRel)
  if (!rendered.startsWith(header)) return undefined
  return rendered.slice(header.length + 1)
}
/** Manifest entries plus every copy discovered by its generated header. */
async function allEntries(root) {
  const entries = copyEntries(root)
  const seen = new Set(entries.map(entry => entry.target))
  for (const entry of await discoverCopies(root)) {
    if (seen.has(entry.target)) continue
    seen.add(entry.target)
    entries.push(entry)
  }
  return entries
}

export async function applySync(root = REPO_ROOT) {
  let written = 0
  for (const { source, target, file, sourceRel } of await allEntries(root)) {
    const rendered = renderCopy(await readFile(source, 'utf8'), file, sourceRel)
    await mkdir(dirname(target), { recursive: true }); await writeFile(target, rendered); written += 1
  }
  return written
}

export async function checkSync(root = REPO_ROOT) {
  const drift = []
  for (const { source, target, file, sourceRel } of await allEntries(root)) {
    let sourceText
    try {
      sourceText = await readFile(source, 'utf8')
    } catch {
      drift.push({ target, reason: `declared shared source is missing: ${sourceRel}` })
      continue
    }
    let rendered
    try { rendered = await readFile(target, 'utf8') } catch { drift.push({ target, reason: 'missing' }); continue }
    const stripped = stripHeader(rendered, file, sourceRel)
    if (stripped === undefined) drift.push({ target, reason: 'header missing or mangled' })
    else if (stripped !== sourceText) drift.push({ target, reason: 'content drifted from shared source' })
  }
  return drift
}
async function main() {
  const mode = process.argv[2]
  if (mode === '--check') {
    const drift = await checkSync()
    if (drift.length) { for (const entry of drift) console.error(`[sync-shared] drift: ${entry.target} (${entry.reason})`); process.exit(1) }
    console.log('[sync-shared] all consumer copies in sync'); return
  }
  if (mode !== undefined) { console.error('usage: node scripts/sync-shared.mjs [--check]'); process.exit(2) }
  console.log(`[sync-shared] wrote ${await applySync()} consumer copies`)
}
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main()
